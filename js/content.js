function mastered(id){ return !!(S && S.mastered && S.mastered.includes(id)); }

function checkMastery(){
  if (!S || !S.path) return;
  const p = path();
  if (mastered(p.id)) return;
  if (!p.perks.length) return;
  if (!p.perks.every(pk => perk(pk.id))) return;
  S.mastered.push(p.id);
  showToast({ name: MASTERY[p.id].name, note: 'Путь освоен · черта навсегда' });
}

